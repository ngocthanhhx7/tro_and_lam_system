import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { log } from 'node:console';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const publicDir = join(root, 'fondend/public');
// Only local, reviewed news assets are processed. Keep the originals intact.
const sources = (await readdir(join(publicDir, 'assets/news'))).sort()
  .filter(name => /\.(?:jpg|jpeg|png|webp)$/u.test(name)).map(name => `/assets/news/${name}`);
sources.push('/assets/photography/chu-dau-heritage.jpg',
  '/assets/editorial/diplomacy-slides/binh-giot-ngoc.webp',
  '/assets/editorial/lifestyle-slides/tea-set.webp', '/assets/video/tro-lam-banner-poster.jpg');
if (sources.length > 24) throw new Error('Review the news allowlist before expanding beyond 24 sources.');
sharp.concurrency(2);
const manifest = {};
const outputs = new Map();
const report = [];
for (const source of sources) {
  const input = await readFile(join(publicDir, source.slice(1)));
  if (input.length > 5 * 1024 * 1024) throw new Error(`Source too large: ${source}`);
  const metadata = await sharp(input, { limitInputPixels: 24_000_000 }).metadata();
  const fingerprint = createHash('sha256').update(input).update('\0webp-q82-alpha100-v1').digest('hex').slice(0, 16);
  const variants = [];
  for (const width of [...new Set([160, 320, 640, 960, 1280, 1600].map(value => Math.min(value, metadata.width)))]) {
    const { data, info } = await sharp(input, { limitInputPixels: 24_000_000 }).rotate()
      .resize({ width, withoutEnlargement: true }).webp({ quality: 82, alphaQuality: 100, effort: 4 }).toBuffer({ resolveWithObject: true });
    const url = `/assets/responsive/v1/${fingerprint}/${info.width}.webp`;
    outputs.set(url, data);
    variants.push({ width: info.width, url });
  }
  manifest[source] = { width: metadata.width, height: metadata.height, variants };
  report.push({ source, originalBytes: input.length, variants: variants.map(v => ({ width: v.width, bytes: outputs.get(v.url).length })) });
}
const derivativeBytes = [...outputs.values()].reduce((sum, data) => sum + data.length, 0);
// This is the combined disk budget for every size, not bytes fetched by a page.
if (derivativeBytes > 8 * 1024 * 1024) throw new Error(`News derivatives exceed the 8 MiB budget: ${derivativeBytes}`);
for (const [url, data] of outputs) {
  const target = join(publicDir, url.slice(1));
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, data);
}
await writeFile(join(root, 'fondend/src/services/catalog/newsImageManifest.js'),
  `// Generated by scripts/prepare-news-images.mjs. Originals are preserved.\nexport const newsImageManifest = ${JSON.stringify(manifest, null, 2)};\n`);
log(JSON.stringify({ sources: sources.length, derivatives: outputs.size, derivativeBytes, report }, null, 2));
