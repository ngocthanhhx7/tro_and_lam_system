import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { log } from 'node:console';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const inputs = join(root, '.codex-tools/owner-photos-20261110');
const publicDir = join(root, 'fondend/public');
const sourceGroups = [
  ['home-lifestyle', [['1.png', 'Hộp trà gốm hoa lam'], ['2.png', 'Bộ trà gốm hoa lam'], ['3.png', 'Bộ đĩa gốm xếp hình hoa']]],
  ['home-diplomacy', [['4.png', 'Bình gốm họa tiết cá chép'], ['5.png', 'Cặp bình Hoa Lam – Tỳ Bà'], ['6.png', 'Bình gốm hoa lam cổ cao'], ['7.png', 'Bình gốm họa tiết chim và hoa'], ['8.png', 'Bình Thiên Nga']]],
  ['originals', [['1.png', 'Cặp bình Hoa Lam – Tỳ Bà'], ['2.png', 'Bình gốm họa tiết hoa và cá'], ['3.png', 'Bình gốm họa tiết cá chép'], ['4.png', 'Bình gốm họa tiết chim'], ['5.png', 'Bình gốm hoa lam cổ cao'], ['6.png', 'Bình gốm họa tiết chim và hoa'], ['7.png', 'Bình Hoa Lam'], ['8.png', 'Bình Tỳ Bà'], ['9.png', 'Bình Thiên Nga']]],
];
const groups = {};
const manifest = {};
const report = [];
let totalBytes = 0;
sharp.concurrency(1);
for (const [group, files] of sourceGroups) {
  groups[group] = [];
  for (const [name, label] of files) {
    const input = await readFile(join(inputs, group, name));
    if (input.length > 48 * 1024 * 1024) throw new Error('Owner image exceeds reviewed 48 MiB input budget');
    const hash = createHash('sha256').update(input).digest('hex');
    const fingerprint = createHash('sha256').update(input).update('\0owner-product-webp-q84-v1').digest('hex').slice(0, 16);
    const source = `/assets/editorial/owner-products-20261110/${group}-${name.replace('.png', '')}-${fingerprint}.webp`;
    const variants = [];
    let dimensions;
    for (const width of [160, 320, 640, 960, 1280, 1600]) {
      const { data, info } = await sharp(input, { limitInputPixels: 40_000_000 }).rotate().resize({ width, withoutEnlargement: true })
        .webp({ quality: 84, effort: 4 }).toBuffer({ resolveWithObject: true });
      const url = width === 1600 ? source : `/assets/responsive/v1/${fingerprint}/${info.width}.webp`;
      const target = join(publicDir, url.slice(1));
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, data);
      totalBytes += data.length;
      variants.push({ width: info.width, url });
      dimensions = { width: info.width, height: info.height };
    }
    manifest[source] = { ...dimensions, variants };
    groups[group].push({ src: source, alt: `${label} - ảnh sản phẩm Gốm Chu Đậu`, label, ...dimensions });
    report.push({ group, file: name, inputSha256: hash, originalBytes: input.length, source, ...dimensions });
  }
}
if (totalBytes > 12 * 1024 * 1024) throw new Error(`Owner image derivatives exceed 12 MiB: ${totalBytes}`);
await writeFile(join(root, 'fondend/src/services/catalog/ownerProductImageManifest.js'),
  `// Generated by scripts/prepare-owner-product-images.mjs from owner-approved Drive photos.\nexport const ownerProductImageManifest = ${JSON.stringify(manifest, null, 2)};\n`);
await writeFile(join(root, 'fondend/src/constants/ownerProductPhotos.js'),
  `// Generated from the owner's 2026-11-10 image request. Labels describe photos, not SKU mappings.\nexport const ownerLifestyleSlides = ${JSON.stringify(groups['home-lifestyle'], null, 2)};\n\nexport const ownerDiplomacySlides = ${JSON.stringify(groups['home-diplomacy'], null, 2)};\n\nexport const ownerAboutProducts = ${JSON.stringify(groups.originals, null, 2)};\n`);
await writeFile(join(inputs, 'generation.json'), JSON.stringify({ sources: report.length, totalDerivativeBytes: totalBytes, report }, null, 2));
log(JSON.stringify({ sources: report.length, variants: report.length * 6, totalDerivativeBytes: totalBytes }));
