import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import { log } from 'node:console';
import sharp from 'sharp';

// Originals and SVG artwork are never overwritten. Run after changing a source.
const root = fileURLToPath(new URL('../', import.meta.url));
const publicDir = join(root, 'fondend/public');
const manifestFile = join(root, 'fondend/src/services/catalog/staticImageManifest.js');
const sources = [];
for (const directory of ['assets/editorial/home-products', 'assets/editorial/story', 'assets/motifs']) {
  for (const name of (await readdir(join(publicDir, directory))).sort()) {
    if (!name.endsWith('.webp') || name.endsWith('-512.webp')) continue;
    sources.push({ source: `/${directory}/${name}`, widths: directory.endsWith('motifs') ? [320, 512] : [320, 640, 960] });
  }
}
sources.push({ source: '/assets/editorial/product-listing-hero.webp', widths: [640, 960] });
if (sources.length > 24) throw new Error('Review the source allowlist before adding more than 24 editorial images.');
const manifest = {};
const outputs = new Map();
let originalBytes = 0;
const report = [];
sharp.concurrency(2);
for (const { source, widths } of sources) {
  const input = await readFile(join(publicDir, source.slice(1)));
  if (input.length > 5 * 1024 * 1024) throw new Error(`Source too large: ${source}`);
  const metadata = await sharp(input, { limitInputPixels: 24_000_000 }).metadata();
  const fingerprint = createHash('sha256').update(input).update('\0webp-q82-alpha100-v1').digest('hex').slice(0, 16);
  const variants = [];
  for (const width of [...new Set(widths.map(value => Math.min(value, metadata.width)))]) {
    const { data, info } = await sharp(input, { limitInputPixels: 24_000_000 })
      .rotate().resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, alphaQuality: 100, effort: 4 }).toBuffer({ resolveWithObject: true });
    const url = `/assets/responsive/v1/${fingerprint}/${info.width}.webp`;
    outputs.set(url, data);
    variants.push({ width: info.width, url });
  }
  originalBytes += input.length;
  manifest[source] = { width: metadata.width, height: metadata.height, variants };
  report.push({ source, originalBytes: input.length, variants: variants.map(variant => ({ width: variant.width, bytes: outputs.get(variant.url).length })) });
}
const totalBytes = [...outputs.values()].reduce((sum, data) => sum + data.length, 0);
if (totalBytes > 5 * 1024 * 1024) throw new Error(`Editorial derivatives exceed the 5 MiB budget: ${totalBytes}`);
for (const [url, data] of outputs) {
  const target = join(publicDir, url.slice(1));
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, data);
}
await writeFile(manifestFile, `// Generated by scripts/prepare-editorial-images.mjs. Source URLs form an explicit allowlist.\nexport const staticImageManifest = ${JSON.stringify(manifest, null, 2)};\n`);
log(JSON.stringify({ sources: sources.length, derivatives: outputs.size, originalBytes, derivativeBytes: totalBytes, report }, null, 2));
