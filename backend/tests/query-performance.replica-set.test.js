import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, createHash } from 'node:crypto';
import mongoose from 'mongoose';
import { CatalogProduct } from '../src/models/catalog/product.model.js';
import { CatalogCategory } from '../src/models/catalog/category.model.js';
import { Cart } from '../src/models/account/cart.model.js';
import { User } from '../src/models/identity/user.model.js';
import { AuthSession } from '../src/models/identity/session.model.js';
import { createMongooseCatalogRepository } from '../src/services/catalog/mongoose-catalog.repository.js';
import { IdentityRepository } from '../src/services/identity/identity.repository.js';
import { createIdentityService } from '../src/services/identity/identity.service.js';
import { AccountRepository } from '../src/services/account/account.repository.js';
import { createAccountService, hashGuestCartToken } from '../src/services/account/account.service.js';
import { createAccountRouter } from '../src/routes/account/account.routes.js';
import { createCatalogService } from '../src/services/catalog/catalog.service.js';
import express from 'express';
import request from 'supertest';

const uri = process.env.QUERY_TEST_REPLICA_SET_URI;
test('optimized queries retain published-category, cart-index and session revocation rules', { skip: !uri }, async () => {
  const target = new URL(uri);
  assert.equal(target.protocol, 'mongodb:');
  assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(target.hostname));
  assert.equal(target.username + target.password + target.search + target.hash, '');
  const dbName = `tro_lam_query_test_${randomBytes(12).toString('hex')}`;
  await mongoose.connect(uri, { dbName });
  try {
    await Promise.all([Cart.createIndexes(), User.createIndexes(), AuthSession.createIndexes()]);
    const categories = ['published', 'draft'].map(status => ({ _id: new mongoose.Types.ObjectId(), status, slug: `query-${status}` }));
    await CatalogCategory.collection.insertMany(categories);
    const products = categories.map((category, index) => ({ _id: new mongoose.Types.ObjectId(), categoryId: category._id, status: 'published', sku: `QUERY-${index}`, slug: `query-product-${index}` }));
    await CatalogProduct.collection.insertMany(products);
    const found = await createMongooseCatalogRepository().findPublishedProductsByIds(products.map(row => String(row._id)));
    assert.deepEqual(found.map(row => String(row._id)), [String(products[0]._id)]);
    assert.equal(found[0]._publishedCategory, undefined);
    const hash = 'a'.repeat(64);
    await Cart.create({ guestTokenHash: hash, items: [], version: 0, expiresAt: new Date(Date.now() + 600000) });
    const e = await Cart.find({ guestTokenHash: { $eq: hash, $type: 'string' } }).explain('executionStats');
    assert.equal(e.executionStats.totalKeysExamined, 1);
    assert.equal(e.executionStats.totalDocsExamined, 1);
    const user = await User.create({ name: 'Query test', emailNormalized: 'query@example.test', passwordHash: 'local-only-hash', role: 'customer', status: 'active' });
    await Cart.create({ userId: user._id, items: [], version: 0, expiresAt: new Date(Date.now() + 600000) });
    assert.equal((await new AccountRepository().findUserCart(String(user._id))).userId, String(user._id));
    const accountService = createAccountService({ ports: { catalogService: createCatalogService({ productRepository: createMongooseCatalogRepository() }) } });
    const app = express();
    app.use(createAccountRouter({ ports: { accountService, identityService: { authenticateSession() { throw new Error('Unexpected authenticated request'); } } },
      config: { csrfSecret: 'local-test-only-secret-at-least-thirty-two-characters', secureCookies: false } }));
    const beforeCount = await Cart.countDocuments();
    const emptyGuest = await request(app).get('/cart').expect(200);
    assert.equal(emptyGuest.body.data.items.length, 0);
    assert.equal(await Cart.countDocuments(), beforeCount, 'GET must not persist an empty guest cart');
    const cookie = emptyGuest.headers['set-cookie'].find(value => value.startsWith('tl_guest_cart=')).split(';')[0];
    const guestToken = decodeURIComponent(cookie.slice('tl_guest_cart='.length));
    await Cart.create({ guestTokenHash: hashGuestCartToken(guestToken), mergedAt: new Date(), items: [], version: 0, expiresAt: new Date(Date.now() + 600000) });
    const rotated = await request(app).get('/cart').set('Cookie', cookie).expect(200);
    assert.notEqual(rotated.headers['set-cookie'].find(value => value.startsWith('tl_guest_cart=')).split(';')[0], cookie);
    assert.equal(rotated.body.data.items.length, 0);
    const token = randomBytes(32).toString('hex');
    const tokenHash = createHash('sha256').update(token).digest('hex');
    await AuthSession.create({ userId: user._id, tokenHash, authVersion: user.authVersion, expiresAt: new Date(Date.now() + 600000), lastSeenAt: new Date() });
    const repository = new IdentityRepository();
    const snapshot = await repository.findSessionWithUser(tokenHash);
    assert.equal(snapshot.user.passwordHash, undefined);
    const service = createIdentityService({ ports: { repository } });
    assert.equal((await service.authenticateSession(token)).id, String(user._id));
    await User.updateOne({ _id: user._id }, { $inc: { authVersion: 1 } });
    await assert.rejects(service.authenticateSession(token), { status: 401, code: 'SESSION_EXPIRED' });
    assert.ok((await AuthSession.findOne({ tokenHash })).revokedAt);
    const blockedToken = randomBytes(32).toString('hex');
    await User.updateOne({ _id: user._id }, { $set: { status: 'blocked' } });
    await AuthSession.create({ userId: user._id, tokenHash: createHash('sha256').update(blockedToken).digest('hex'), authVersion: user.authVersion + 1, expiresAt: new Date(Date.now() + 600000) });
    await assert.rejects(service.authenticateSession(blockedToken), { status: 403, code: 'ACCOUNT_BLOCKED' });
  } finally { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); }
});
